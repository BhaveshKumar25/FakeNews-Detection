    confidence = data.get("confidence", 0.0)
    conf_pct = round(confidence * 100, 1)
    is_uncertain = data.get("is_uncertain", False)
    input_type = html.escape(data.get("input_type", "Text"))
    source_url = html.escape(data.get("source_url", "N/A"))
    source_domain = html.escape(data.get("source_domain", "N/A"))
